import type { ApiPropertyOptions } from '@nestjs/swagger';
import { ORDER_ITEM_MAX_QUANTITY, ORDER_STATUSES } from './order.constant';

const ORDER_ID_PARAM = {
  name: 'id',
  description: 'The order id (UUID v4).',
  example: '3f2a9e10-6f1d-4a2b-9c3e-5d7a1b2c4e8f',
};

export const ORDER_SWAGGER = {
  API_TAG: 'Orders',

  CREATE: {
    operation: {
      summary: 'Place an order',
      description:
        'Creates a `pending` order. The total is computed by the service from ' +
        'the items; it is never taken from the request.',
    },
    responses: {
      201: { description: 'Order created.' },
      400: { description: 'The body failed validation.' },
    },
  },

  FIND_ALL: {
    operation: { summary: 'List orders', description: 'Newest first.' },
    responses: {
      200: { description: 'Every order.' },
    },
  },

  FIND: {
    operation: { summary: 'Get one order' },
    params: [ORDER_ID_PARAM],
    responses: {
      200: { description: 'The order.' },
      400: { description: '`id` is not a UUID.' },
      404: { description: 'No order with that id.' },
    },
  },

  CANCEL: {
    operation: {
      summary: 'Cancel an order',
      description: 'Only a `pending` order can be cancelled.',
    },
    params: [ORDER_ID_PARAM],
    responses: {
      200: { description: 'The order, now `cancelled`.' },
      404: { description: 'No order with that id.' },
      409: { description: 'The order is no longer `pending`.' },
    },
  },

  REMOVE: {
    operation: { summary: 'Delete an order' },
    params: [ORDER_ID_PARAM],
    responses: {
      204: { description: 'Order deleted.' },
      404: { description: 'No order with that id.' },
    },
  },
} as const;

